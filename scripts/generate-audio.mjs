async function downloadAudio(text, outputPath, splitText = false) {
  try {
    const dir = path.dirname(outputPath);
    if (!fs.existsSync(dir)) {
      fs.mkdirSync(dir, { recursive: true });
    }

    let readText = text;
    if (splitText) {
       const segments = text.match(/[\u0621-\u064A][\u064B-\u065F]*/g);
       if (segments) {
         readText = segments.join('   '); 
       }
    }

    const url = googleTTS.getAudioUrl(readText, {
      lang: 'ar',
      slow: true,
      host: 'https://translate.google.com',
    });

    const response = await fetch(url);
    const buffer = await response.arrayBuffer();
    fs.writeFileSync(outputPath, Buffer.from(buffer));
    console.log(`Saved: ${outputPath}`);
  } catch (error) {
    console.error(`Failed to download audio for ${text}:`, error);
  }
}

async function processList(list, day, prefix, splitText) {
  for (let i = 0; i < list.length; i++) {
    const dayStr = String(day).padStart(2, '0');
    const idxStr = String(i + 1).padStart(2, '0');
    const outputPath = `./public/audio/elifba/dersler/gun-${dayStr}/${prefix}-${idxStr}.mp3`;
    
    if (!fs.existsSync(outputPath)) {
        await downloadAudio(list[i], outputPath, splitText);
        await new Promise(r => setTimeout(r, 1000));
    } else {
        console.log(`Skipped existing: ${outputPath}`);
    }
  }
}

